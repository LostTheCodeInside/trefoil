// Package libxray embeds Xray-core behind a gomobile-friendly API.
//
// It exists for one reason: sing-box cannot do post-quantum REALITY (ML-DSA-65),
// and some providers now require it. Rather than replace the tunnel, Xray is run as
// a plain SOCKS5 server on loopback and sing-box dials it as an ordinary outbound —
// so the TUN, DNS, routing and per-app handling all stay exactly where they were.
//
// Only gomobile-representable types cross this boundary: strings, ints, bools,
// errors, and interfaces whose methods use the same.
package libxray

import (
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"strings"
	"sync"
	"syscall"

	"golang.org/x/crypto/curve25519"

	"github.com/xtls/xray-core/core"
	"github.com/xtls/xray-core/infra/conf/serial"
	"github.com/xtls/xray-core/transport/internet"

	// Registers every protocol, transport and codec Xray knows about.
	_ "github.com/xtls/xray-core/main/distro/all"
)

// Protector hands a socket to the platform so it can be kept out of the tunnel.
// Implemented on Android by VpnService.protect.
type Protector interface {
	Protect(fd int32) bool
}

var (
	access     sync.Mutex
	instance   *core.Instance
	controller = new(protectController)
)

// protectController holds the current Protector behind a lock.
//
// Xray's dialer controllers can only be registered once per process and can never
// be removed, so registration happens once and the target is swapped underneath.
// Without this, a second Start would stack another controller onto the same dialer.
type protectController struct {
	sync.RWMutex
	protector Protector
	once      sync.Once
}

func (c *protectController) set(protector Protector) {
	c.Lock()
	c.protector = protector
	c.Unlock()

	c.once.Do(func() {
		internet.RegisterDialerController(func(network, address string, conn syscall.RawConn) error {
			c.RLock()
			protector := c.protector
			c.RUnlock()
			if protector == nil {
				return nil
			}
			var protectErr error
			err := conn.Control(func(fd uintptr) {
				if !protector.Protect(int32(fd)) {
					protectErr = fmt.Errorf("protect(%d) refused by the platform", fd)
				}
			})
			if err != nil {
				return err
			}
			return protectErr
		})
	})
}

func (c *protectController) clear() {
	c.Lock()
	c.protector = nil
	c.Unlock()
}

// Start brings up Xray with the given JSON config. Starting while already running
// replaces the previous instance, so callers cannot leak one by forgetting to stop.
func Start(configJSON string, protector Protector) error {
	access.Lock()
	defer access.Unlock()

	if instance != nil {
		instance.Close()
		instance = nil
	}

	config, err := serial.LoadJSONConfig(strings.NewReader(configJSON))
	if err != nil {
		return fmt.Errorf("parse config: %w", err)
	}

	// Registered before Start: Xray may dial as soon as it comes up, and an
	// unprotected socket at that moment would be routed straight back into the tunnel.
	controller.set(protector)

	newInstance, err := core.New(config)
	if err != nil {
		controller.clear()
		return fmt.Errorf("create instance: %w", err)
	}
	if err = newInstance.Start(); err != nil {
		newInstance.Close()
		controller.clear()
		return fmt.Errorf("start instance: %w", err)
	}

	instance = newInstance
	return nil
}

// Stop is safe to call when nothing is running.
func Stop() error {
	access.Lock()
	defer access.Unlock()

	controller.clear()
	if instance == nil {
		return nil
	}
	err := instance.Close()
	instance = nil
	return err
}

func IsRunning() bool {
	access.Lock()
	defer access.Unlock()
	return instance != nil
}

// Test reports whether a config is valid without starting anything.
func Test(configJSON string) error {
	config, err := serial.LoadJSONConfig(strings.NewReader(configJSON))
	if err != nil {
		return fmt.Errorf("parse config: %w", err)
	}
	testInstance, err := core.New(config)
	if err != nil {
		return fmt.Errorf("create instance: %w", err)
	}
	return testInstance.Close()
}

func Version() string {
	return core.Version()
}

// GenerateWireGuardKeyPair returns "privateKey\npublicKey", both base64.
//
// Lives in this package only because it is the one Go package this app binds; the
// alternative was a Dart cryptography dependency, and key material is better
// generated by a vetted implementation and handed over once than assembled in the
// Dart heap.
//
// Used to register a Cloudflare WARP account, which is WireGuard underneath.
func GenerateWireGuardKeyPair() (string, error) {
	var private [32]byte
	if _, err := rand.Read(private[:]); err != nil {
		return "", fmt.Errorf("read random: %w", err)
	}
	// Curve25519 clamping, as WireGuard requires: clear the low three bits, clear
	// the top bit, set the second-highest.
	private[0] &= 248
	private[31] &= 127
	private[31] |= 64

	public, err := curve25519.X25519(private[:], curve25519.Basepoint)
	if err != nil {
		return "", fmt.Errorf("derive public key: %w", err)
	}
	return base64.StdEncoding.EncodeToString(private[:]) + "\n" +
		base64.StdEncoding.EncodeToString(public), nil
}
